#!/usr/bin/env node
/**
 * Snapshots the SaaSquatch GraphQL schema used by the canned (story) client.
 *
 *   node scripts/sync-canned-schema.js <path to saasquatch repo>
 *
 * The schema lives in the private saasquatch monorepo at
 * packages/saasquatch-core/conf/graphql/schema/SaaSquatch.graphql.
 */
const { execFileSync } = require("child_process");
const fs = require("fs");
const path = require("path");

const SCHEMA_PATH = "packages/saasquatch-core/conf/graphql/schema/SaaSquatch.graphql";
const repo = process.argv[2];
if (!repo) {
  console.error("Usage: node scripts/sync-canned-schema.js <path to saasquatch repo>");
  process.exit(1);
}

const sdl = fs.readFileSync(path.join(repo, SCHEMA_PATH), "utf8");
const commit = execFileSync(
  "git",
  ["-C", repo, "log", "-1", "--format=%H %cs", "--", SCHEMA_PATH],
  { encoding: "utf8" }
).trim();

const out = `// Generated by scripts/sync-canned-schema.js. Do not edit.
// Source: saasquatch/saasquatch ${SCHEMA_PATH} @ ${commit}
export const SAASQUATCH_SCHEMA_SOURCE = ${JSON.stringify(commit)};
export const SAASQUATCH_SCHEMA_SDL = ${JSON.stringify(sdl)};
`;
fs.writeFileSync(path.join(__dirname, "../src/canned/schema.ts"), out);
console.log(`Wrote src/canned/schema.ts from ${commit} (${sdl.length} bytes)`);
